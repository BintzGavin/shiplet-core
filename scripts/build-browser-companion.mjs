import { readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const folder = path.join(root, "browser-companion");
const files = {};
for (const name of (await readdir(folder)).sort()) if (/\.(json|js|html|css)$/.test(name)) files[name] = await readFile(path.join(folder, name), "utf8");
// A deterministic, uncompressed ZIP avoids an additional runtime dependency.
function crc32(bytes) { let crc = 0xffffffff; for (const byte of bytes) { crc ^= byte; for (let bit = 0; bit < 8; bit++) crc = (crc >>> 1) ^ ((crc & 1) ? 0xedb88320 : 0); } return (crc ^ 0xffffffff) >>> 0; }
const local = [], directory = [];
let offset = 0;
for (const [name, text] of Object.entries(files)) {
  const fileName = Buffer.from(name), data = Buffer.from(text), crc = crc32(data);
  const header = Buffer.alloc(30); header.writeUInt32LE(0x04034b50); header.writeUInt16LE(20, 4); header.writeUInt32LE(crc, 14); header.writeUInt32LE(data.length, 18); header.writeUInt32LE(data.length, 22); header.writeUInt16LE(fileName.length, 26);
  local.push(header, fileName, data);
  const entry = Buffer.alloc(46); entry.writeUInt32LE(0x02014b50); entry.writeUInt16LE(20, 4); entry.writeUInt16LE(20, 6); entry.writeUInt32LE(crc, 16); entry.writeUInt32LE(data.length, 20); entry.writeUInt32LE(data.length, 24); entry.writeUInt16LE(fileName.length, 28); entry.writeUInt32LE(offset, 42);
  directory.push(entry, fileName); offset += header.length + fileName.length + data.length;
}
const central = Buffer.concat(directory), end = Buffer.alloc(22); end.writeUInt32LE(0x06054b50); end.writeUInt16LE(Object.keys(files).length, 8); end.writeUInt16LE(Object.keys(files).length, 10); end.writeUInt32LE(central.length, 12); end.writeUInt32LE(offset, 16);
const zip = Buffer.concat([...local, central, end]);
const assets = {
  "/capture/editor.js": files["editor.js"],
  "/capture/client.js": await readFile(path.join(root, "src/browser/capture-client.js"), "utf8"),
};
const output = `// Generated by scripts/build-browser-companion.mjs. Do not edit.\nexport const BROWSER_COMPANION_ZIP = ${JSON.stringify(zip.toString("base64"))};\nexport const BROWSER_CAPTURE_ASSETS: Record<string, string> = ${JSON.stringify(assets, null, 2)};\n`;
if (process.argv.includes("--check")) {
  if (await readFile(path.join(root, "src/generated-browser-companion.ts"), "utf8") !== output) throw new Error("Browser companion assets are stale. Run node scripts/build-browser-companion.mjs");
} else await writeFile(path.join(root, "src/generated-browser-companion.ts"), output);
