import { readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import react from "@vitejs/plugin-react";
import { build } from "vite";

import { createPlatformClientBuildConfig } from "./platform-client-build-config.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, ".shiplet-platform-client");
const generatedModule = path.join(root, "src/generated-platform-client.ts");
const clientEntries = [
	{
		assetPath: "/assets/platform/shiplets.js",
		entry: path.join(root, "src/platform/shiplets-client.tsx"),
		fileName: "shiplets.js",
	},
	{
		assetPath: "/assets/platform/inbox.js",
		entry: path.join(root, "src/platform/inbox-client.tsx"),
		fileName: "inbox.js",
	},
	{
		assetPath: "/assets/platform/feedback.js",
		entry: path.join(root, "src/platform/feedback-client.tsx"),
		fileName: "feedback.js",
	},
];

await rm(outDir, { recursive: true, force: true });

const generatedAssets = {};

for (const clientEntry of clientEntries) {
	await build(
		createPlatformClientBuildConfig({
			entry: clientEntry.entry,
			fileName: clientEntry.fileName,
			outDir,
			plugins: [react()],
			root,
		}),
	);

	generatedAssets[clientEntry.assetPath] = await readFile(
		path.join(outDir, clientEntry.fileName),
		"utf8",
	);
}

const generated = `// Generated by scripts/build-platform-client.mjs.
// Do not edit by hand.

export const PLATFORM_CLIENT_ASSETS = {
${Object.entries(generatedAssets)
	.map(([assetPath, source]) => `\t${JSON.stringify(assetPath)}: ${JSON.stringify(source)},`)
	.join("\n")}
} as const;
`;

await writeFile(generatedModule, generated);
await rm(outDir, { recursive: true, force: true });
