import assert from "node:assert/strict";
import { readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import react from "@vitejs/plugin-react";
import { build } from "vite";

import { createPlatformClientBuildConfig } from "./platform-client-build-config.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, ".shiplet-plugin-app");
const generatedModule = path.join(root, "src/generated-plugin-app.ts");
const scriptFileName = "plugin-app.js";
const styleFileName = "plugin-app.css";

export function createPluginAppBuildConfig({ plugins = [] } = {}) {
	const config = createPlatformClientBuildConfig({
		entry: path.join(root, "src/plugin-app/main.tsx"),
		fileName: scriptFileName,
		outDir,
		plugins: [react(), ...plugins],
		root,
	});
	config.build.lib.cssFileName = path.basename(styleFileName, ".css");
	config.build.cssCodeSplit = false;
	config.build.assetsInlineLimit = Number.MAX_SAFE_INTEGER;
	config.logLevel = "warn";
	return config;
}

// Inline content must not be able to close its own element early.
export function escapeInlineScript(source) {
	return source.replace(/<\/(script)/gi, "<\\/$1").replace(/<!--/g, "<\\!--");
}

export function escapeInlineStyle(source) {
	return source.replace(/<\/(style)/gi, "\\3c/$1");
}

const BOOT_SKELETON = `<main class="sl-app"><ul class="sl-list" aria-busy="true" aria-label="Shiplet">${'<li class="sl-row sl-row-skeleton" aria-hidden="true"><span class="sl-skeleton sl-skeleton-title"></span><span class="sl-skeleton sl-skeleton-meta"></span></li>'.repeat(3)}</ul></main>`;

export function renderPluginAppDocument({ script, style }) {
	return [
		"<!doctype html>",
		'<html lang="en">',
		"<head>",
		'<meta charset="utf-8">',
		'<meta name="viewport" content="width=device-width,initial-scale=1">',
		"<title>Shiplet</title>",
		`<style>${escapeInlineStyle(style)}</style>`,
		"</head>",
		"<body>",
		// Static skeleton so the frame is never blank while the bundle parses;
		// React replaces it on first render.
		`<div id="shiplet-app">${BOOT_SKELETON}</div>`,
		`<script type="module">${escapeInlineScript(script)}</script>`,
		"</body>",
		"</html>",
	].join("");
}

async function main() {
	await rm(outDir, { recursive: true, force: true });
	try {
		await build(createPluginAppBuildConfig());
		const script = await readFile(path.join(outDir, scriptFileName), "utf8");
		const style = await readFile(path.join(outDir, styleFileName), "utf8");
		const html = renderPluginAppDocument({ script: script.trim(), style: style.trim() });

		// The MCP App iframe CSP blocks external resources: everything is inline.
		assert.doesNotMatch(html, /<script[^>]*\ssrc\s*=/i, "plugin app must not load external scripts");
		assert.doesNotMatch(html, /<link[^>]*\shref\s*=/i, "plugin app must not load external stylesheets");
		assert.doesNotMatch(html, /@import\s/i, "plugin app CSS must not @import");
		assert.doesNotMatch(style, /url\(\s*["']?(?:https?:)?\/\//i, "plugin app CSS must not reference remote URLs");
		assert.equal(html.match(/<\/script/gi)?.length, 1, "inline script was not escaped");

		const generated = `// Generated by scripts/build-plugin-app.mjs.
// Do not edit by hand.

export const PLUGIN_APP_HTML = ${JSON.stringify(html)};
`;
		await writeFile(generatedModule, generated);
		process.stdout.write(
			`Wrote src/generated-plugin-app.ts (${Buffer.byteLength(html, "utf8")} bytes).\n`,
		);
	} finally {
		await rm(outDir, { recursive: true, force: true });
	}
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	await main();
}
