import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceDirectory = path.join(root, "public", "brand", "why-shiplet");
const assets = {
	defaultReviewFlow: "default-review-flow.webp",
	durableObjectBenefits: "durable-object-benefits.webp",
	researchEvidenceBoard: "research-evidence-board.webp",
	shipletRootHero: "shiplet-root-hero.webp",
	shipletRootRuntime: "shiplet-root-runtime.webp",
	ticketAcceptanceRunner: "ticket-acceptance-runner.webp",
};

const encoded = await Promise.all(
	Object.entries(assets).map(async ([key, filename]) => [
		key,
		(await readFile(path.join(sourceDirectory, filename))).toString("base64"),
	]),
);

const generated = `// Generated by scripts/generate-why-shiplet-assets.mjs. Do not edit by hand.

export const WHY_SHIPLET_ASSETS = {
${encoded.map(([key, value]) => `\t"${key}": "${value}"`).join(",\n")}
} as const;
`;

await writeFile(
	path.join(root, "src", "generated-why-shiplet-assets.ts"),
	generated,
);
